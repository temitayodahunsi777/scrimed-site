#!/usr/bin/env node

import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

import { getP34AdaptiveGovernanceSummary } from "../app/lib/scrimed-p34/index.ts";

const check = process.argv.includes("--check");
const summary = getP34AdaptiveGovernanceSummary();
const gatePath = "artifacts/p34/P34_GATE_MATRIX.json";
const validationPath = "artifacts/p34/P34_VALIDATION_REPORT.json";

const gateMatrix = {
  schemaVersion: "scrimed-p34-gate-matrix-v1",
  candidateBinding: "exact candidate binding generated by release tooling after local commit",
  statusesAllowed: ["PASS", "OPERATOR_REQUIRED", "BLOCKED", "FAIL"],
  counts: summary.gateCounts,
  gates: summary.gateMatrix,
  nonPhiPilotStatus: "local-controls-pass-independent-review-required",
  phiCapablePilotStatus: "blocked",
  productionStatus: "blocked",
  providerCallsExecuted: false,
  migrationExecuted: false,
  deploymentAuthorized: false,
  externalDistributionAuthorized: false,
  summaryHash: summary.summaryHash
};

const checks = [
  { id: "capability-registry-integrity", passed: /^[0-9a-f]{64}$/.test(summary.registry.registryHash), evidence: summary.registry.registryHash },
  { id: "unknown-capability-default-deny", passed: summary.registry.unknownCapabilityDecision === "deny", evidence: summary.registry.registryVersion },
  { id: "deterministic-first-route", passed: summary.taskRoute.selectedTechnique === "validation-rules" && summary.taskRoute.providerCallExecuted === false, evidence: summary.taskRoute.decisionHash },
  { id: "context-provenance-and-conflict-retention", passed: summary.context.chunks.every((chunk) => chunk.sourceSpanIds.length > 0) && summary.context.conflictGroupIds.length > 0, evidence: summary.context.envelopeHash },
  { id: "grounded-claims", passed: summary.claimValidation.decision !== "BLOCK", evidence: summary.claimValidation.validationHash },
  { id: "dicom-export-fails-closed", passed: summary.dicomPrivacy.exportAuthorized === false && summary.dicomPrivacy.researchUseAuthorized === false, evidence: summary.dicomPrivacy.manifestHash },
  { id: "governance-chain", passed: summary.governance.verification.valid, evidence: summary.governance.verification.chainHash },
  { id: "quality-no-auto-promotion", passed: summary.evaluation.automaticPromotionAllowed === false && summary.evaluation.promotionEligibleForHumanReview, evidence: summary.evaluation.decisionHash },
  { id: "task-level-economics", passed: summary.finOps.costPerCompletedTaskUsd !== null && summary.finOps.providerCallExecuted === false, evidence: summary.finOps.decisionHash },
  { id: "offline-placement", passed: summary.placement.selectedPlacementId === "placement-local-sandbox-v1" && summary.placement.phiRouteAuthorized === false, evidence: summary.placement.decisionHash },
  { id: "high-risk-flags-default-off", passed: [summary.featureFlags.externalProviderCallsEnabled, summary.featureFlags.dicomExportEnabled, summary.featureFlags.livePhiEnabled, summary.featureFlags.consequentialExecutionEnabled, summary.featureFlags.productionPromotionEnabled].every((value) => value === false), evidence: "five high-risk flags disabled" },
  { id: "release-authority-retained", passed: summary.phiProcessed === false && summary.clinicalActionAuthorized === false && summary.deploymentAuthorized === false && summary.customerActivationAuthorized === false && summary.externalDistributionAuthorized === false, evidence: summary.summaryHash }
];

const validationReport = {
  schemaVersion: "scrimed-p34-validation-report-v1",
  scope: "deterministic synthetic p.34 domain contracts",
  generatedAt: "2026-08-15T00:00:00.000Z",
  status: checks.every((item) => item.passed) ? "PASS" : "FAIL",
  checkCount: checks.length,
  passedCount: checks.filter((item) => item.passed).length,
  failedCount: checks.filter((item) => !item.passed).length,
  checks,
  externalEvidenceVerified: false,
  productionAuthorityGranted: false,
  summaryHash: summary.summaryHash
};

const outputs = [
  [gatePath, `${JSON.stringify(gateMatrix, null, 2)}\n`],
  [validationPath, `${JSON.stringify(validationReport, null, 2)}\n`]
];

if (check) {
  for (const [filePath, expected] of outputs) {
    assert.equal(await readFile(filePath, "utf8"), expected, `${filePath} is stale`);
  }
  console.log(`pass SCRIMED p.34 artifact integrity (${outputs.length} artifacts)`);
} else {
  for (const [filePath, content] of outputs) await writeFile(filePath, content, "utf8");
  console.log(`generated SCRIMED p.34 artifacts (${outputs.length})`);
}
